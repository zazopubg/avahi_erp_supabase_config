/// واجهة موحّدة لأي "استراتيجية" تُحدِّد *متى* تُشغَّل دورة مزامنة
/// (بمعزل تماماً عن *كيفية* تنفيذها، وهو ما يتولاه
/// `outbox/outbox_processor.dart` عبر `sync_engine.dart`).
///
/// يمكن تشغيل أكثر من استراتيجية معاً بأمان (مثال: [ContinuousSync]
/// دورية كل فترة ثابتة + [ForegroundSync] فورية عند استعادة التركيز،
/// كلتاهما تستدعيان نفس `onTrigger` دون تعارض — `SyncEngine` نفسه
/// يضمن عدم تداخل دورتي معالجة في آن واحد).
abstract class SyncStrategy {
  /// يبدأ الاستراتيجية، مستدعياً [onTrigger] في كل مرة يجب فيها تشغيل
  /// دورة مزامنة. آمن للاستدعاء المتكرر (يستبدل `onTrigger` السابق إن
  /// وُجد بدل تكديس عدة اشتراكات).
  void start(Future<void> Function() onTrigger);

  /// يوقف الاستراتيجية ويحرر أي موارد (Timer/Observer) بشكل نظيف.
  void stop();

  bool get isActive;
}
